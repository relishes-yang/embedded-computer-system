def find_min_peaches_optimized():
    """
    优化版：从后往前推，提高计算效率
    该算法通过数学推理，从第五只猴子分完后的状态反推回初始状态
    """
    # 第五只猴子分之前有x个桃子
    # x = 5a + 1，剩下4a（因为分5份多1个，拿走1份后剩4份）
    # 第四只猴子分之前有y个桃子
    # y = 5b + 1，剩下4b = x（第四只分完后剩x个桃子给第五只）
    # 所以4b = x，即b = x/4，那么y = 5*(x/4) + 1 = (5x)/4 + 1
    # 为了保证b是整数，x必须能被4整除

    # 从x开始搜索，x必须同时满足两个条件：
    # 1. x % 5 == 1 （第五只猴子分的时候，桃子数除以5余1）
    # 2. x % 4 == 0 （剩余的桃子数能被4整除，用于反推上一只猴子的桃子数）

    x = 6  # 从第一个满足x % 5 == 1的数开始（1, 6, 11, 16...），这里选择6
    while True:  # 开始无限循环搜索
        if x % 5 == 1 and x % 4 == 0:  # 检查当前x是否同时满足两个条件
            # 如果满足条件，则开始反向计算第四只猴子分之前的桃子数
            # 根据 y = (5x)/4 + 1 的公式计算
            y = (5 * x) // 4 + 1

            # 验证y是否也符合同样的规律（第四只猴子也能分）
            if y % 5 == 1 and y % 4 == 0:
                # 如果y符合条件，则计算第三只猴子分之前的桃子数
                # 根据 z = (5y)/4 + 1 的公式计算
                z = (5 * y) // 4 + 1

                # 验证z是否也符合规律
                if z % 5 == 1 and z % 4 == 0:
                    # 如果z符合条件，则计算第二只猴子分之前的桃子数
                    # 根据 w = (5z)/4 + 1 的公式计算
                    w = (5 * z) // 4 + 1

                    # 验证w是否也符合规律
                    if w % 5 == 1 and w % 4 == 0:
                        # 如果w符合条件，则计算第一只猴子分之前的桃子数（原始桃子数）
                        # 根据 v = (5w)/4 + 1 的公式计算
                        v = (5 * w) // 4 + 1

                        # 验证v是否也符合规律（第一只猴子分的时候也满足条件）
                        if v % 5 == 1 and v % 4 == 0:
                            # 如果所有条件都满足，说明找到了正确的初始桃子数
                            return v  # 返回计算出的初始桃子数
        x += 5  # 如果当前x不满足条件，则增加5，这样可以保证x % 5 == 1始终成立
        # 因为如果x % 5 == 1，那么(x+5) % 5 == 1也成立


# 调用函数找到最小的初始桃子数
min_peaches = find_min_peaches_optimized()
# 输出结果
print(f"海滩上原来最少有 {min_peaches} 个桃子")