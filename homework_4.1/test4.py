# 1. 定义斐波那契数列的开头两个数字（固定的）
fib_list = [0, 1]

# 2. 循环10次，生成后面的10个数字
# 因为我们需要 0,1 之后的10个数，所以循环10次
for i in range(10):
    # 3. 新数字 = 列表最后一个数字 + 列表倒数第二个数字
    new_number = fib_list[-1] + fib_list[-2]
    # 4. 把新数字加到列表里
    fib_list.append(new_number)

# 5. 列表前两个是0和1，我们要后面的10个，所以从第3个开始取（索引2）
result = fib_list[2:]
# 6. 打印结果
print("0和1之后的10个斐波那契数：", result)